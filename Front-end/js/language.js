const mmdTextNodeOriginals = new WeakMap();
const mmdAttributeOriginals = new WeakMap();
const mmdDynamicText = new Map();
const mmdLanguageSelect = document.querySelector("#siteLanguage");
const mmdOriginalTitle = document.title;
let mmdCurrentLanguage = "en";
function mmdTranslateText(source, values = {}) {
    const translated = mmdCurrentLanguage === "fr"
        ? mmdFrenchTranslations[source] ?? source
        : source;
    return translated.replace(/\{(\w+)\}/g, (placeholder, key) => Object.prototype.hasOwnProperty.call(values, key)
        ? String(values[key])
        : placeholder);
}
function mmdSetTranslatedText(element, source, values) {
    element.setAttribute("translate", "no");
    mmdDynamicText.set(element, { source, values });
    element.textContent = mmdTranslateText(source, values);
}
function mmdTranslatePage(language, persist) {
    mmdCurrentLanguage = language;
    document.documentElement.lang = language;
    document.title = mmdTranslateText(mmdOriginalTitle);
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
        const textNode = node;
        const parent = textNode.parentElement;
        if (parent &&
            !parent.closest('[translate="no"]') &&
            !parent.closest("#siteLanguage") &&
            !["SCRIPT", "STYLE"].includes(parent.tagName)) {
            if (!mmdTextNodeOriginals.has(textNode)) {
                mmdTextNodeOriginals.set(textNode, textNode.nodeValue ?? "");
            }
            const original = mmdTextNodeOriginals.get(textNode) ?? "";
            const trimmed = original.trim();
            if (trimmed) {
                const leading = original.slice(0, original.indexOf(trimmed));
                const trailing = original.slice(original.indexOf(trimmed) + trimmed.length);
                textNode.nodeValue = `${leading}${mmdTranslateText(trimmed)}${trailing}`;
            }
        }
        node = walker.nextNode();
    }
    const attributeElements = document.querySelectorAll("[alt], [title], [placeholder], [aria-label]");
    for (const element of attributeElements) {
        if (element.closest('[translate="no"]')) {
            continue;
        }
        let originals = mmdAttributeOriginals.get(element);
        if (!originals) {
            originals = new Map();
            mmdAttributeOriginals.set(element, originals);
        }
        for (const attribute of ["alt", "title", "placeholder", "aria-label"]) {
            if (!element.hasAttribute(attribute)) {
                continue;
            }
            if (!originals.has(attribute)) {
                originals.set(attribute, element.getAttribute(attribute) ?? "");
            }
            element.setAttribute(attribute, mmdTranslateText(originals.get(attribute) ?? ""));
        }
    }
    const description = document.querySelector('meta[name="description"]');
    if (description) {
        if (!mmdAttributeOriginals.has(description)) {
            mmdAttributeOriginals.set(description, new Map([["content", description.content]]));
        }
        const originalDescription = mmdAttributeOriginals.get(description)?.get("content") ?? "";
        description.content = mmdTranslateText(originalDescription);
    }
    if (mmdLanguageSelect) {
        mmdLanguageSelect.value = language;
    }
    for (const [element, message] of mmdDynamicText) {
        element.textContent = mmdTranslateText(message.source, message.values);
    }
    if (persist) {
        localStorage.setItem("mmd-language", language);
    }
    window.dispatchEvent(new CustomEvent("mmd-language-change", { detail: language }));
}
window.mmdLanguage = () => mmdCurrentLanguage;
window.mmdTranslateText = mmdTranslateText;
window.mmdSetTranslatedText = mmdSetTranslatedText;
const mmdSavedLanguage = localStorage.getItem("mmd-language");
const mmdInitialLanguage = mmdSavedLanguage === "fr" || mmdSavedLanguage === "en"
    ? mmdSavedLanguage
    : navigator.language.toLowerCase().startsWith("fr")
        ? "fr"
        : "en";
mmdTranslatePage(mmdInitialLanguage, false);
mmdLanguageSelect?.addEventListener("change", () => {
    if (mmdLanguageSelect.value === "fr" || mmdLanguageSelect.value === "en") {
        mmdTranslatePage(mmdLanguageSelect.value, true);
    }
});
